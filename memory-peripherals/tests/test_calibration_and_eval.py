"""Synthetic calibration and the controller-trace harness.

The calibration traces are generated by the model. Recovering a parameter
from them shows the fitter works. It is not a measurement of silicon.
"""

from __future__ import annotations

from dataclasses import replace

from memperiph.calibrate import (
    apply_hyperram_latency,
    apply_rpc_cl,
    collect_hyperram,
    hyperram_mismatches,
    recover_hyperram_latency,
    recover_min_gap,
    recover_rpc_rl,
)
from memperiph.evaluate import dumps, evaluate_rpc_trace, run_safe_probes
from memperiph.hyperram import HyperRAMDevice, HyperRAMParams
from memperiph.rpcdram import RpcDramFased, profile_1600
from memperiph.util import AxiRequest


def test_fitter_recovers_latency_and_gap_from_a_synthetic_trace():
    truth = HyperRAMParams()
    dev = HyperRAMDevice(truth)
    # Variable latency, so some samples are 1x and the fixed-latency
    # power-on transaction is 2x. Both must vote for L = 7.
    dev.read(0, 32)
    dev.write(0x1000, bytes([0x8F, 0x27]), space="reg")
    for _ in range(6):
        dev.read(0, 32)
        dev.write(64, b"\x10\x20")
    obs = collect_hyperram(dev)
    assert recover_hyperram_latency(obs) == 7
    assert recover_min_gap(obs) == truth.tCSHI_ck

    # A wrong latency code disagrees. Applying the fitted code clears it.
    wrong = apply_hyperram_latency(truth, 6)
    assert (wrong.cr0_reset >> 4) & 0xF == 0x1
    wrong_dev = HyperRAMDevice(wrong)
    wrong_dev.read(0, 32)
    # Same script shape: one fixed-latency read. Compare that one sample
    # against the truth's first sample.
    mismatches = hyperram_mismatches(obs[:1], collect_hyperram(wrong_dev)[:1])
    assert mismatches, "a latency of 6 must not match a latency of 7"
    fitted = apply_hyperram_latency(wrong, recover_hyperram_latency(obs))
    fitted_dev = HyperRAMDevice(fitted)
    fitted_dev.read(0, 32)
    assert hyperram_mismatches(obs[:1], collect_hyperram(fitted_dev)[:1]) == []


def test_rpc_row_hit_latency_recovers_rl():
    p = profile_1600()
    m = RpcDramFased(p, page="open")
    m.run([AxiRequest(False, 0, 32)], outstanding=1)
    hits = []
    for i in range(4):
        done = m.run([AxiRequest(False, 32 * (i + 1), 32)], outstanding=1)[0]
        assert done.row_hit
        hits.append(done.latency)
    assert recover_rpc_rl(hits) == p.rl_ck
    updated = apply_rpc_cl(p, p.rl_ck)
    assert updated.cl == p.cl
    shifted = apply_rpc_cl(replace(p, cl=8), 12)
    assert shifted.cl == 11


def test_rpc_trace_harness_separates_legal_and_illegal_commands():
    legal = evaluate_rpc_trace([
        {"op": "ACT", "cycle": 0, "bank": 0, "row": 1},
        {"op": "RD", "cycle": 16, "bank": 0, "row": 1, "col": 0, "bc": 0},
    ])
    assert legal["pass"]
    assert legal["n_violations"] == 0
    illegal = evaluate_rpc_trace([
        {"op": "RD", "cycle": 0, "bank": 0, "col": 0, "bc": 0},
    ])
    assert not illegal["pass"]
    assert illegal["violations"][0]["code"] == "row-closed"
    text = dumps(illegal)
    assert "\"pass\": false" in text


def test_safe_probes_pass_on_the_reference_models():
    result = run_safe_probes()
    assert result["pass"], result
    assert result["hyperram"]["n_violations"] == 0
    assert result["rpc"]["n_violations"] == 0
